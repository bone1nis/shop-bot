@pytest.mark.parametrize("question,facts,must,must_not,handoff", CASES, ids=[c[0] for c in CASES])
def test_rules(question, facts, must, must_not, handoff):
    result = rules.answer(question)
    assert result["facts"] == facts
    for fragment in must:
        assert fragment.lower() in result["answer"].lower()
    for fragment in must_not:
        assert fragment.lower() not in result["answer"].lower()
    assert result["handoff"] is handoff


@pytest.mark.parametrize("question", [c[0] for c in CASES])
def test_rules_pass_llm_validator(question):
    """Шаблоны правил проходят ту же проверку, что и ответы LLM: ни одного числа не из базы."""
    assert validate(rules.answer(question), question) is None


@pytest.mark.parametrize(
    "answer,facts,reason",
    [
        ("Гарантия на X1 — 24 месяца.", [], "числа не из базы"),
        ("Как правило, деньги возвращаются за 7 дней.", ["F3"], "числа не из базы"),
        ("Скорее всего, курьер будет у вас вечером.", ["F2"], "неуверенная формулировка"),
        ("Деньги придут за 3 рабочих дня.", ["F9"], "неизвестные факты"),
        ("Заказ 1842 привезём около 20:30.", ["F2"], "числа не из базы"),
        ("X1 стоят 2 490 ₽.", [], "числа не из базы"),  # цена без ссылки на F1
    ],
)
def test_validator_rejects_hallucinations(answer, facts, reason):
    result = {"answer": answer, "facts": facts, "found": True, "handoff": False}
    assert reason in validate(result, "доставка заказа 1842")


def test_validator_accepts_grounded_answer():
    result = {"answer": "Деньги придут на ту же карту за 3 рабочих дня.", "facts": ["F3"], "found": True, "handoff": False}
    assert validate(result, "когда вернутся деньги?") is None
